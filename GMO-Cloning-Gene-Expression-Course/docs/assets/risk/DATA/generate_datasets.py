def non_target():
    """Non-target arthropod survival exposed to Bt vs non-Bt pollen - 3 species."""
    rows = []
    # (species, functional group, control_survival, bt_effect, n)
    spec = [("honeybee_adult", "pollinator", 0.93, -0.005, 30),
            ("ladybeetle_adult", "predator", 0.90, -0.003, 30),
            ("green_lacewing_larva", "predator", 0.85, -0.020, 30),
            ("parasitoid_wasp", "parasitoid", 0.88, -0.006, 30),
            ("springtail", "detritivore", 0.92, -0.001, 30)]
    for sp, grp, base, eff, n in spec:
        for cond in ("non-Bt_pollen", "Bt_pollen"):
            for rep in range(1, n // 10 + 1):         # 10 individuals per replicate cage
                p = base + (eff if cond == "Bt_pollen" else 0.0)
                alive = rng.binomial(10, min(max(p, 0.01), 0.99))
                rows.append({"species": sp, "functional_group": grp,
                             "treatment": cond, "replicate": rep,
                             "n_exposed": 10, "alive": alive,
                             "proportion_alive": round(alive / 10, 2)})
    df = pd.DataFrame(rows)
    txt = ("# Exercise 2 - Non-target organism survival (SIMULATED)\n"
           "# Design: caged individuals of 5 arthropod species fed pollen from a Bt\n"
           "# crop or a near-isogenic non-Bt line; 10 individuals per cage, 3 cages\n"
           "# per species x treatment; survival scored after a fixed exposure period.\n"
           "# Question: is there evidence of direct toxicity for any species? How do\n"
           "# effect sizes compare with natural cage-to-cage variation?\n"
           "# Columns: species, functional_group, treatment, replicate, n_exposed, alive, proportion_alive\n")
