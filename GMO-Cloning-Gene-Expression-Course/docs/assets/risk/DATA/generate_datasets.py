def dose_response():
    """Dose-response for a non-target larva fed a purified protein (4-parameter-style)."""
    doses = np.array([0, 1, 3, 10, 30, 100, 300], dtype=float)   # ng/cm2 diet surface
    rows = []
    for dose in doses:
        # sigmoid: top=0.95, bottom=0.15, IC50=40, slope=1.6
        p = 0.15 + (0.95 - 0.15) / (1 + (dose / 40.0) ** 1.6) if dose > 0 else 0.95
        for rep in range(1, 9):                                   # 12 larvae per replicate
            alive = rng.binomial(12, p)
            rows.append({"dose_ng_per_cm2": dose, "replicate": rep,
                         "n_larvae": 12, "alive": int(alive),
                         "proportion_alive": round(alive / 12, 3)})
    df = pd.DataFrame(rows)
    txt = ("# Exercise 8 - Dose-response relationship (SIMULATED)\n"
           "# Design: laboratory larval feeding study with a purified protein at 7\n"
           "# dose levels (including zero-dose control), 8 replicate dishes x 12\n"
           "# larvae. Sigmoid (hill) relationship with IC50 ~ 40 ng/cm2 (illustrative).\n"
           "# Question: fit a dose-response curve; estimate IC50; explain why the\n"
           "# zero-dose control anchors the top of the curve.\n"
           "# Columns: dose_ng_per_cm2, replicate, n_larvae, alive, proportion_alive\n")
    w("dose-response", "dose_response_larvae.csv", df, HEADER + txt)


