# ---------------------------------------------------------------- Exercise 1
def gene_flow():
    """Pollen-mediated outcrossing frequencies vs distance from GM field edge."""
    dist = np.array([1, 2, 5, 10, 20, 50, 100, 200], dtype=float)          # m
    # Exponential decay model: f = a * exp(-b*d) + floor
    a, b, floor = 0.028, 0.09, 0.0002
    true = a * np.exp(-b * dist) + floor
    rows = []
    for d, t in zip(dist, true):
        for rep in range(1, 6):                       # 5 replicate plots per distance
            # binomial sampling: ~40,000 seeds screened per replicate
            n_seeds = int(rng.integers(36000, 44000))
            hits = rng.binomial(n_seeds, t)
            rows.append({"distance_m": d, "replicate": rep,
                         "seeds_screened": n_seeds, "hybrid_seeds": hits,
                         "flow_frequency": round(hits / n_seeds, 7)})
    df = pd.DataFrame(rows)
    txt = ("# Exercise 1 - Pollen-mediated gene flow (SIMULATED)\n"
           "# Design: field plots at 8 distances from a GM pollen source, 5 replicate\n"
           "# plots each; ~40,000 offspring seeds screened per replicate for the\n"
           "# herbicide-tolerance marker (expected-heterozygote survival assay).\n"
           "# Question: how does outcrossing frequency decay with distance, and what\n"
           "# is an appropriate isolation-distance recommendation?\n"
           "# Columns: distance_m, replicate, seeds_screened, hybrid_seeds, flow_frequency\n")
    w("gene-flow", "pollen_flow_distance.csv", df, HEADER + txt)


