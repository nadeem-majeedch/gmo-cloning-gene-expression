def uncertainty():
    """Sensitivity-analysis input table for a simple gene-flow -> risk estimate."""
    n = 400
    isolation = rng.uniform(0, 200, n)                 # m isolation distance
    outcross_base = rng.uniform(0.001, 0.03, n)        # baseline outcrossing
    wild_area = rng.uniform(0, 100, n)                 # ha of compatible wild hosts nearby
    refuge = rng.uniform(0, 30, n)                     # % refuge compliance
    # Toy model: expected hybrid seed rain per ha of wild host (illustrative).
    # NOTE for teaching: in this toy parameterization isolation distance spans the
    # widest effective range (exp(-0.05*d), 0-200 m), so it dominates variance;
    # see Exercise 10 interpretation about range-dependence of sensitivity.
    hybrid_load = (outcross_base * 1e4 * np.exp(-0.05 * isolation)
                   * (1 + wild_area / 25) * (1 + refuge / 60))
    noise = rng.normal(1, 0.08, n)
    df = pd.DataFrame({
        "run": np.arange(1, n + 1),
        "isolation_distance_m": isolation.round(1),
        "baseline_outcross_rate": outcross_base.round(5),
        "wild_host_area_ha": wild_area.round(1),
        "refuge_compliance_pct": refuge.round(1),
        "hybrid_seed_rain_index": (hybrid_load * noise).round(3),
    })
    txt = ("# Exercise 10 - Uncertainty / sensitivity analysis (SIMULATED)\n"
           "# 400 Monte-Carlo-style runs of a toy gene-flow exposure model.\n"
           "# Inputs: isolation distance, baseline outcrossing, nearby wild-host\n"
           "# area, refuge compliance. Output: relative hybrid seed-rain index.\n"
           "# Question: which input drives output variance most? What does that\n"
           "# imply for where to spend assessment effort and monitoring money?\n"
           "# Columns: run, isolation_distance_m, baseline_outcross_rate,\n"
           "#          wild_host_area_ha, refuge_compliance_pct, hybrid_seed_rain_index\n")
    w("uncertainty", "sensitivity_runs.csv", df, HEADER + txt)


