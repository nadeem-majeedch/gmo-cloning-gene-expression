def herbicide_weeds():
    """Herbicide-resistant weed patches discovered per scouting season, by field history."""
    years = np.arange(2012, 2026)
    rows = []
    for system, base_rate in (("continuous_glyphosate", 0.55), ("rotated_systems", 0.10)):
        k = base_rate * 12                                    # patches per season scale
        for y in years:
            patches = rng.poisson(k * (1 + 0.18 * (y - 2012)) if system.startswith("cont") else k)
            rows.append({"year": int(y), "management_system": system,
                         "fields_scouted": 120,
                         "new_resistant_patches": int(patches)})
    df = pd.DataFrame(rows)
    txt = ("# Exercise 4 - Herbicide-resistant weed emergence (SIMULATED)\n"
           "# Design: two crop-management systems scouted over 14 seasons;\n"
           "# response = new glyphosate-resistant patches detected per season\n"
           "# (120 fields scouted per system per year).\n"
           "# Question: compare emergence rates; what does this imply for herbicide\n"
           "# diversity / integrated weed management recommendations?\n"
           "# Columns: year, management_system, fields_scouted, new_resistant_patches\n")
    w("resistance", "herbicide_resistant_weeds.csv", df, HEADER + txt)


