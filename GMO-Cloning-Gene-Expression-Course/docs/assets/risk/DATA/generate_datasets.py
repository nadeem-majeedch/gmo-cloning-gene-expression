# ---------------------------------------------------------------- Exercise 3
def bt_resistance():
    """Resistance allele frequency over generations under two management regimes.

    Simplified deterministic viability-selection model for a RECESSIVE resistance
    allele (classic high-dose/refuge teaching model):
        q' = q / wbar,  wbar = F + (1-F) * [(1-s)(1-q)^2 + 2q(1-q) + q^2]
    where F = refuge fraction (no selection on Bt-susceptible genotypes there)
    and s = fitness cost of susceptible homozygotes on Bt tissue.
    """
    gens = np.arange(0, 21)
    s_cost, q0 = 0.30, 0.0001
    rows = []
    for regime, F in (("no_refuge", 0.0), ("structured_refuge_50pct", 0.5)):
        q = q0
        for g in gens:
            n_moths = int(rng.integers(900, 1100))
            res = rng.binomial(n_moths, q)
            rows.append({"generation": int(g), "regime": regime,
                         "moths_genotyped": n_moths,
                         "resistance_alleles": res,
                         "allele_frequency": round(res / n_moths, 6)})
            wbar = F + (1 - F) * ((1 - s_cost) * (1 - q) ** 2 + 2 * q * (1 - q) + q ** 2)
            q = min(q / wbar, 0.95)
    df = pd.DataFrame(rows)
    txt = ("# Exercise 3 - Bt resistance allele frequency over time (SIMULATED)\n"
           "# Model: recessive resistance allele under simplified viability selection;\n"
           "# susceptible homozygotes suffer fitness cost s=0.30 on Bt tissue; refuge\n"
           "# fraction F = 0 (no_refuge) or 0.5 (structured_refuge_50pct, chosen to\n"
           "# illustrate selection dilution - real refuge sizes vary by system).\n"
           "# Starting frequency q0 = 0.0001; per-generation frequency estimated by\n"
           "# genotyping ~1000 moths (F2-screen concept; binomial sampling noise).\n"
           "# Question: how does a structured refuge delay resistance buildup? When\n"
           "# would a monitoring program first detect a practical problem?\n"
           "# Columns: generation, regime, moths_genotyped, resistance_alleles, allele_frequency\n")
    w("resistance", "bt_resistance_frequency.csv", df, HEADER + txt)


