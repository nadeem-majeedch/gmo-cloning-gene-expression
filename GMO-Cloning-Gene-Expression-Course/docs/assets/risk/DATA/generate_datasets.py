def soil_microbes():
    """Soil bacterial OTU counts (subset) under Bt and non-Bt maize, 3 time points."""
    otus = [f"OTU{i:03d}" for i in range(1, 41)]
    times = ["day_30", "day_60", "day_90"]
    rows = []
    for t_i, t in enumerate(times):
        for trt in ("Bt_maize", "nonBt_maize"):
            for plot in range(1, 7):                       # 6 replicate plots
                for otu in otus:
                    lam = np.exp(rng.normal(2.2, 0.9))     # lognormal-ish abundance
                    if otu in ("OTU003", "OTU017") and t == "day_60" and trt == "Bt_maize":
                        lam *= 1.5                        # one mild seasonal signal
                    count = rng.poisson(lam)
                    rows.append({"time_point": t, "treatment": trt, "plot": plot,
                                 "otu": otu, "read_count": int(count)})
    df = pd.DataFrame(rows)
    txt = ("# Exercise 5 - Soil bacterial community subset (SIMULATED)\n"
           "# Design: rhizosphere samples under Bt vs non-Bt maize at 3 growth\n"
           "# stages, 6 replicate plots; counts are reads of 40 representative OTUs\n"
           "# (amplicon-style). Compare alpha diversity and treatment differences.\n"
           "# Question: do Bt and non-Bt rhizospheres differ? How does temporal\n"
           "# variation compare with any treatment effect?\n"
           "# Columns: time_point, treatment, plot, otu, read_count\n")
    w("soil", "soil_otu_counts.csv", df, HEADER + txt)


