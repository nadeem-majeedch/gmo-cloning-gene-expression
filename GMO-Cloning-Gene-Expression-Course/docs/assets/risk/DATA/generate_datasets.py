def exposure():
    """Cry protein concentration across environmental compartments over a season."""
    days = np.arange(0, 161, 10)
    rows = []
    for comp, c0, k in (("rhizosphere_soil", 18.0, 0.045),
                        ("crop_debris", 42.0, 0.020),
                        ("adjacent_runoff_water", 0.9, 0.12),
                        ("pollen_trap", 6.0, 0.0)):
        for d in days:
            conc = c0 * np.exp(-k * d) if comp != "pollen_trap" else c0 * (1 + 0.3 * np.sin(d / 9))
            meas = max(conc * rng.normal(1, 0.12), 0.05)
            rows.append({"day": int(d), "compartment": comp,
                         "protein_ng_per_g_or_L": round(float(meas), 3)})
    df = pd.DataFrame(rows)
    txt = ("# Exercise 7 - Environmental exposure concentration (SIMULATED)\n"
           "# Design: measured (illustrative) Bt-protein levels in 4 environmental\n"
           "# compartments over one growing season (ng/g soil or tissue; ng/L water;\n"
           "# relative units for pollen traps).\n"
           "# Question: which compartment sustains the longest exposure? What\n"
           "# decay half-life does each show? How would you bound worst-case dose?\n"
           "# Columns: day, compartment, protein_ng_per_g_or_L\n")
    w("exposure", "environmental_concentrations.csv", df, HEADER + txt)


